export function trUi(text: string, lang: "es" | "en", vars?: Record<string, string | number>): string {
  let out = lang === "en" ? (UI_EN[text] ?? text) : text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}
